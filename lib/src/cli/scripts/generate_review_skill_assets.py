#!/usr/bin/env python3
"""Regenerate the compiled-in review skills (48b).

    python3 scripts/generate_review_skill_assets.py        # run from anywhere

Reads every shipped review skill and rewrites the one generated translation
unit:

    assets/review-skills/*.md          ->  source/data/contracts/assets_review_skills.cpp
    assets/review-skills/exclude.txt   ->  (the same unit: the diff-exclusion list, 48c)

The FILES are the source of truth: edit them, run this, and commit both.
tests/data/contracts/assets_test.cpp fails the build the moment a literal
and its file differ, or a file has no literal -- the contract the recipes,
the kits and the symphony starters keep. Each skill is one raw string, far
under MSVC's 16 380-byte literal limit; the script refuses one that is not.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "assets" / "review-skills"
OUT = ROOT / "source" / "data" / "contracts" / "assets_review_skills.cpp"

DELIMITER = "SKILL"
LIMIT = 15_000


def generate() -> str:
    files = sorted(SKILLS.glob("*.md"))
    if not files:
        raise SystemExit(f"{SKILLS}: no review skills to compile in")
    out = [
        "#include <array>",
        "#include <span>",
        "#include <string_view>",
        "",
        '#include "contracts/assets.h"',
        "",
        "// GENERATED by scripts/generate_review_skill_assets.py from",
        "// lib/src/cli/assets/review-skills/*.md -- the shipped review skills (48b).",
        "// The shipped files and these literals are byte-identical, and",
        "// tests/data/contracts/assets_test.cpp fails the build the moment they",
        "// drift. Edit the FILES, then regenerate; never edit a literal here.",
        "",
        "namespace apogee::harness {",
        "// clang-format off",
        "namespace {",
        "",
        f"constexpr std::array<BundledReviewSkill, {len(files)}> kReviewSkills{{{{",
    ]
    for path in files:
        text = path.read_text(encoding="utf-8")
        if f"){DELIMITER}\"" in text:
            raise SystemExit(f"{path}: contains the raw-string terminator ){DELIMITER}\"")
        if len(text.encode("utf-8")) > LIMIT:
            raise SystemExit(f"{path}: over {LIMIT} bytes -- split it or chunk the literal")
        out.append(f'    {{.name = "{path.stem}", .text = R"{DELIMITER}({text}){DELIMITER}"}},')
    exclusions = (SKILLS / "exclude.txt").read_text(encoding="utf-8")
    if f"){DELIMITER}\"" in exclusions:
        raise SystemExit("exclude.txt: contains the raw-string terminator")
    out += [
        "}};",
        "",
        f'constexpr std::string_view kExclusions = R"{DELIMITER}({exclusions}){DELIMITER}";',
        "",
        "}  // namespace",
        "",
        "// clang-format on",
        "",
        "std::span<const BundledReviewSkill> bundled_review_skills() noexcept {",
        "    return kReviewSkills;",
        "}",
        "",
        "std::string_view bundled_review_exclusions() noexcept {",
        "    return kExclusions;",
        "}",
        "",
        "}  // namespace apogee::harness",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    OUT.write_text(generate(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
