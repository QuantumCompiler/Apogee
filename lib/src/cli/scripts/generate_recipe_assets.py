#!/usr/bin/env python3
"""Regenerate the compiled-in task recipes (40c).

    python3 scripts/generate_recipe_assets.py        # run from anywhere

Reads every shipped recipe file and rewrites the one generated translation unit:

    assets/recipes/*.yaml  ->  source/data/contracts/assets_recipes.cpp

The FILES are the source of truth: edit them, run this, and commit both.
tests/data/contracts/assets_test.cpp fails the build the moment a literal
and its file differ, or a file has no literal -- the contract the bundled
agents, the kits and the symphony starters keep. Each recipe is one raw string, far under
MSVC's 16 380-byte literal limit; the script refuses one that is not.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPECS = ROOT / "assets" / "recipes"
OUT = ROOT / "source" / "data" / "contracts" / "assets_recipes.cpp"

DELIMITER = "RECIPE"
LIMIT = 15_000


def generate() -> str:
    files = sorted(SPECS.glob("*.yaml"))
    if not files:
        raise SystemExit(f"{SPECS}: no recipes to compile in")
    out = [
        "#include <array>",
        "#include <span>",
        "#include <string_view>",
        "",
        '#include "contracts/assets.h"',
        "",
        "// GENERATED by scripts/generate_recipe_assets.py from",
        "// lib/src/cli/assets/recipes/*.yaml -- the shipped task recipes (40c).",
        "// The shipped files and these literals are byte-identical, and",
        "// tests/data/contracts/assets_test.cpp fails the build the moment they",
        "// drift. Edit the FILES, then regenerate; never edit a literal here.",
        "",
        "namespace apogee::harness {",
        "// clang-format off",
        "namespace {",
        "",
        f"constexpr std::array<BundledRecipe, {len(files)}> kRecipes{{{{",
    ]
    for path in files:
        text = path.read_text(encoding="utf-8")
        if f"){DELIMITER}\"" in text:
            raise SystemExit(f"{path}: contains the raw-string terminator ){DELIMITER}\"")
        if len(text.encode("utf-8")) > LIMIT:
            raise SystemExit(f"{path}: over {LIMIT} bytes -- split it or chunk the literal")
        out.append(f'    {{.name = "{path.stem}", .text = R"{DELIMITER}({text}){DELIMITER}"}},')
    out += [
        "}};",
        "",
        "}  // namespace",
        "",
        "// clang-format on",
        "",
        "std::span<const BundledRecipe> bundled_recipes() noexcept {",
        "    return kRecipes;",
        "}",
        "",
        "}  // namespace apogee::harness",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    OUT.write_text(generate(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
