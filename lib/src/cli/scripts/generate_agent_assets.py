#!/usr/bin/env python3
"""Regenerate the compiled-in bundled agents (Milestone X; 40a).

    python3 scripts/generate_agent_assets.py        # run from anywhere

Reads each bundled agent's shipped files and rewrites the one generated
translation unit:

    assets/prompts/<name>.txt            \\
    assets/schemas/<name>-output.json     >  source/data/contracts/assets_agents.cpp

The FILES are the source of truth for the texts, and AGENTS below for which
agents are bundled, in which order, described how: edit them, run this, and
commit both. tests/data/contracts/assets_test.cpp fails the build the moment a
literal and its file differ, or a prompt file has no agent -- the contract the
kits and the symphony starters keep. Each text is one raw string, far under
MSVC's 16 380-byte literal limit; the script refuses one that is not.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROMPTS = ROOT / "assets" / "prompts"
SCHEMAS = ROOT / "assets" / "schemas"
OUT = ROOT / "source" / "data" / "contracts" / "assets_agents.cpp"

LIMIT = 15_000

# The bundled agents, in the order `agents list` shows them, each with the
# description it lists with.
AGENTS = [
    (
        "security-review",
        "Offline, diff-first security review of the branch under review: findings with impact, "
        "remediation and CWE, and a verdict",
    ),
    (
        "release-notes",
        "Categorized release notes (features, fixes, breaking changes) for a commit range or the "
        "branch under review",
    ),
    (
        "merge-request",
        "Merge-readiness review of the branch under review against acceptance criteria and ADRs from "
        "a collection; peer review or self review with a paste-ready description",
    ),
    (
        "code-review",
        "Correctness and simplification review of a diff, a file or the branch under review: "
        "findings with location, severity and a suggested fix, and a verdict",
    ),
    (
        "test-gaps",
        "The behaviors a diff, a file or the branch under review adds that no test would notice "
        "breaking, each with a suggested test",
    ),
    (
        "doc-drift",
        "Documentation statements the branch under review made untrue, checked against a "
        "collection of the project's docs (--rag) and its files, each with an edit",
    ),
    (
        "meeting-minutes",
        "Minutes from a meeting transcript: decisions, action items with owner and due date, "
        "and open questions",
    ),
]


def literal(path: Path, delimiter: str) -> str:
    text = path.read_text(encoding="utf-8")
    if f"){delimiter}\"" in text:
        raise SystemExit(f"{path}: contains the raw-string terminator ){delimiter}\"")
    if len(text.encode("utf-8")) > LIMIT:
        raise SystemExit(f"{path}: over {LIMIT} bytes -- shorten it or chunk the literal")
    return f'R"{delimiter}({text}){delimiter}"'


def cpp_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate() -> str:
    named = {name for name, _ in AGENTS}
    for path in sorted(PROMPTS.glob("*.txt")):
        if path.stem not in named:
            raise SystemExit(f"{path}: a prompt with no bundled agent -- add it to AGENTS")
    out = [
        "#include <array>",
        "#include <span>",
        "#include <string_view>",
        "",
        '#include "contracts/assets.h"',
        "",
        "// GENERATED by scripts/generate_agent_assets.py from",
        "// lib/src/cli/assets/prompts/<name>.txt and assets/schemas/<name>-output.json",
        "// -- the bundled agents (Milestone X; 40a). The shipped files and these",
        "// literals are byte-identical, and tests/data/contracts/assets_test.cpp fails",
        "// the build the moment they drift. Edit the FILES, then regenerate; never",
        "// edit a literal here.",
        "",
        "namespace apogee::harness {",
        "// clang-format off",
        "namespace {",
        "",
        f"constexpr std::array<BundledAgent, {len(AGENTS)}> kBundled{{{{",
    ]
    for name, description in AGENTS:
        prompt = literal(PROMPTS / f"{name}.txt", "PROMPT")
        schema = literal(SCHEMAS / f"{name}-output.json", "SCHEMA")
        out += [
            "    {",
            f"        .name = {cpp_string(name)},",
            f"        .description = {cpp_string(description)},",
            f"        .prompt = {prompt},",
            f"        .schema = {schema},",
            "    },",
        ]
    out += [
        "}};",
        "",
        "}  // namespace",
        "",
        "// clang-format on",
        "",
        "std::span<const BundledAgent> bundled_agents() noexcept {",
        "    return kBundled;",
        "}",
        "",
        "}  // namespace apogee::harness",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    OUT.write_text(generate(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
